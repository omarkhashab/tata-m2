"""The late-start test: the consumer is started only *after* the producer has finished.

    python -m kestrel_m2.stream.late_start_test --rate 400

Steps (all against the real broker):

1. reset the three topics and the stream tables (a clean, repeatable run);
2. run the producer to completion: every message, then EOS on each partition;
3. only then start the consumer with group ``kestrel-tata`` and
   ``auto_offset_reset='earliest'``. The group has **no committed offsets**, so Kafka
   applies auto_offset_reset: the consumer starts at offset 0 of every partition and
   reads the whole replay, although it was not running while the data was produced;
4. probe: a **fresh group** with ``auto_offset_reset='latest'`` starts at the log end
   and reads nothing (it would only see messages produced after it joined);
5. re-run group ``kestrel-tata``: it now has committed offsets (committed after each
   write), so auto_offset_reset is **not consulted** and it reads nothing new: no
   message is processed twice;
6. run the window job on the curated topic.

Writes ``output/stream/late_start_test.md`` with the evidence.
"""

from __future__ import annotations

import argparse
import json
import time

from .. import config
from . import consumer, producer, windows


def main(argv=None) -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--rate", type=float, default=400.0)
    args = p.parse_args(argv)
    out = config.OUT_DIR / "stream"
    out.mkdir(parents=True, exist_ok=True)

    t = time.time()
    prod = producer.run(config.RAW_DIR / "stream_events.json", config.KAFKA_BOOTSTRAP, args.rate, reset=True)
    prod_done = time.time()
    (out / "producer_summary.json").write_text(json.dumps(prod, indent=2))
    print("producer finished:", json.dumps(prod))

    group = config.CONSUMER_GROUP
    first = consumer.run(group, "earliest", idle_timeout=30, reset=True)
    (out / "consumer_summary.json").write_text(json.dumps(first, indent=2, default=str))
    if first["watermark_example"]:
        (out / "watermark_caught_example.json").write_text(json.dumps(first["watermark_example"], indent=2))
    print("consumer (late start, earliest):", json.dumps({k: v for k, v in first.items() if k != "watermark_example"},
                                                         default=str))

    probe = consumer.run(f"{group}-latest-probe-{int(time.time())}", "latest", idle_timeout=10)
    rerun = consumer.run(group, "earliest", idle_timeout=10)
    win = windows.run(config.WINDOW_GROUP + f"-{int(time.time())}", idle_timeout=20)
    (out / "windows_summary.json").write_text(json.dumps(win, indent=2, default=str))

    def row(name, s):
        return (f"| {name} | `{s['group_id']}` | `{s['auto_offset_reset']}` | {s['first_offset_read'] or '-'} | "
                f"{s['messages_read']:,} | {s['accepted']:,} | {s['rejected']:,} | {s['committed_offsets']} |")

    md = [
        "# Late-start test", "",
        "Generated by `python -m kestrel_m2.stream.late_start_test`. The producer replayed the whole feed and "
        f"exited **{round(prod_done - t, 1)} s** after the start; only then was the consumer started.", "",
        f"Producer: {prod['messages']:,} messages + {prod['eos_records']} EOS records at a fixed "
        f"{prod['rate_target_per_s']:g} msg/s (achieved {prod['rate_achieved_per_s']} msg/s), per partition "
        f"{prod['per_partition']}; `stated_goal` fingerprinted on {prod.get('stated_goal_fingerprinted', 0):,} "
        f"records, {prod.get('non_object_elements', 0)} non-object elements forwarded as-is.", "",
        "| run | group | auto_offset_reset | first offset read per partition | messages read | accepted | rejected "
        "| committed offsets at exit |",
        "|---|---|---|---|---:|---:|---:|---|",
        row("1 late start", first), row("2 probe, new group", probe), row("3 same group again", rerun), "",
        "## What `auto_offset_reset` did", "",
        "* **Run 1.** The group `kestrel-tata` had never committed an offset, so on its first poll Kafka applied "
        "`auto_offset_reset='earliest'`. The first offset read is 0 on every partition, so the consumer read the "
        "entire replay although it was started after the producer had finished. Messages are retained on the broker, "
        "and a consumer does not have to be running when they are produced.",
        "* **Run 2.** A new group with `auto_offset_reset='latest'` starts at the end of each partition. It read "
        "nothing because nothing was produced after it joined. With `latest`, the late-start test would have "
        "silently lost the whole feed.",
        "* **Run 3.** The same group again reads nothing: its offsets were committed after each successful write "
        "(Kafka topics flushed, then the PostgreSQL transaction committed), and committed offsets take precedence. "
        "`auto_offset_reset` only applies when a group has no valid committed offset.", "",
        "## Consumer outcome (run 1)", "",
        "```json", json.dumps({k: v for k, v in first.items() if k not in ("watermark_example",)}, indent=2,
                              default=str), "```", "",
        "## A record caught by the watermark", "",
        "```json", json.dumps(first["watermark_example"], indent=2), "```", "",
        "## Tumbling one-minute windows per tenant (curated topic)", "",
        "```json", json.dumps({k: v for k, v in win.items() if k != "late_examples"}, indent=2, default=str), "```",
    ]
    (out / "late_start_test.md").write_text("\n".join(md), encoding="utf-8")
    print(f"wrote {out / 'late_start_test.md'}")
    if not (first["first_offset_read"] and all(v == 0 for v in first["first_offset_read"].values())
            and probe["messages_read"] == 0 and rerun["messages_read"] == 0):
        raise SystemExit("late-start test: unexpected offsets (see late_start_test.md)")


if __name__ == "__main__":
    main()
